"""Generate mirrored feat_req blocks for the Open SOME/IP specification.

Each requirement in the specification becomes a local `feat_req` carrying its
identifier and its source location, but not its text: the specification is
licensed Community-Spec-1.0 and its wording is not reproduced here. The
`hash` field holds "<document>:<line>", which `needs_string_links` in
docs/conf.py renders as a link to that line of the pinned specification blob.

Line numbers come from the vendored export, never by hand.
"""

import argparse
import json
import re

HEADER = """..
   # *******************************************************************************
   # Copyright (c) 2026 Contributors to the Eclipse Foundation
   #
   # See the NOTICE file(s) distributed with this work for additional
   # information regarding copyright ownership.
   #
   # This program and the accompanying materials are made available under the
   # terms of the Apache License Version 2.0 which is available at
   # https://www.apache.org/licenses/LICENSE-2.0
   #
   # SPDX-License-Identifier: Apache-2.0
   # *******************************************************************************

.. Generated by tools/extneeds/generate_spec_requirements.py -- do not edit.

Open SOME/IP Specification Requirements
#######################################

Requirements mirrored from the Open SOME/IP specification. Only identifiers and
source locations are held here; the specification text is not reproduced.
Follow ``hash`` to read a requirement at its source.
"""

REQTYPE = {"Requirement": "Functional", "Information": "Non-Functional"}

BLOCK = """
.. feat_req:: Open SOME/IP {part} {number}
   :id: {id}
   :reqtype: {reqtype}
   :security: {security}
   :safety: {safety}
   :status: valid
   :version: 1
   :valid_from: {valid_from}
   :satisfied_by: {satisfied_by}
   :hash: {docname}:{lineno}

   Mirrored from the Open SOME/IP specification; text not reproduced.
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("src", help="vendored needs export")
    ap.add_argument("dst", help="reStructuredText file to write")
    ap.add_argument("--satisfied-by", default="feat__someip_gateway")
    ap.add_argument("--valid-from", default="v0.1.0")
    args = ap.parse_args()

    doc = json.load(open(args.src))
    needs = next(iter(doc["versions"].values()))["needs"]

    out = [HEADER]
    for key in sorted(needs):
        need = needs[key]
        match = re.fullmatch(r"feat_req_(someip[a-z]*)_(\d+)", need["id"])
        if not match:
            raise SystemExit(f"unexpected identifier {need['id']!r} in vendored needs")
        if not need.get("docname") or not need.get("lineno"):
            raise SystemExit(f"{need['id']}: missing docname/lineno, link would be wrong")
        out.append(
            BLOCK.format(
                part=match.group(1),
                number=match.group(2),
                id=f"feat_req__extspec__{match.group(1)}_{match.group(2)}",
                reqtype=REQTYPE.get(need.get("reqtype"), "Non-Functional"),
                security="NO" if need.get("security") == "TBD" else need.get("security", "NO"),
                safety="QM" if need.get("safety") == "TBD" else need.get("safety", "QM"),
                valid_from=args.valid_from,
                satisfied_by=args.satisfied_by,
                docname=need["docname"],
                lineno=need["lineno"],
            )
        )

    open(args.dst, "w").write("".join(out))
    print(f"generated {len(needs)} mirrored requirements")


if __name__ == "__main__":
    main()
